"""Alembic environment: runs migrations over the app's own async engine URL."""
import asyncio
from alembic import context
from sqlalchemy.ext.asyncio import create_async_engine
from app.config import settings

config = context.config
URL = config.get_main_option("sqlalchemy.url") or settings.DATABASE_URL  # tests point this at a scratch database


def run_sync(connection):
    context.configure(connection=connection, target_metadata=None)  # migrations are written by hand, not autogenerated
    with context.begin_transaction():
        context.run_migrations()


async def run_async():
    engine = create_async_engine(URL)
    async with engine.connect() as connection:
        await connection.run_sync(run_sync)
    await engine.dispose()


if context.is_offline_mode():
    context.configure(url=URL, literal_binds=True, target_metadata=None)
    with context.begin_transaction():
        context.run_migrations()
else:
    asyncio.run(run_async())
